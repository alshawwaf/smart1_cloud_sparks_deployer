#!/usr/bin/env python3
"""
Smart-1 Cloud Management API Operations

Handles Check Point Management Server operations including:
- Gateway registration (cloud token) and configuration
- Policy installation
- Session management

API Documentation:
https://sc1.checkpoint.com/documents/latest/APIs/

Spark gateways are created as documented in the Smart-1 Cloud Administration Guide
("Example: Adding a Simple Gateway with the Web API"):
- add-simple-gateway with the Spark 'hardware' (for example "1800 Appliances"),
  'hardware-subtype', 'version', 'trust-method': 'cloud_token' and 'auto-generate-ip'.
  The response contains the cloud token for 'connect maas auth-token' on the appliance.
  Spark objects get 'global and automatic' interface topology by default.
- set-simple-gateway with the one-time password and 'trust-settings.initiation-phase':
  'when_gateway_connects', so the appliance pulls its certificate ('fetch certificate').
  The SIC name is generated by the management server.
These parameters require Management API 2.1 (Smart-1 Cloud R82.20).
"""

from typing import Dict, Optional, List
import requests
import json
import time
from .logger_main import log
from tqdm import tqdm

# Management API version that introduced cloud tokens and 'trust-settings' (R82.20)
REQUIRED_API_VERSION = (2, 1)
SIC_POLL = 15  # seconds between SIC state checks
DEFAULT_TIMEOUT = 60  # seconds for each HTTP request
TASK_TIMEOUT = 1800  # seconds to wait for a publish or install-policy task


class ManagementAPI:
    """Client for Check Point Gateway operations"""

    def __init__(self, instance: str, context: str, api_key: str, timeout: int = DEFAULT_TIMEOUT):
        self.base_url = f"https://{instance}.maas.checkpoint.com/{context}/web_api"
        self.api_key = api_key
        self.timeout = timeout
        self.sid: Optional[str] = None
        self.api_version: Optional[str] = None
        self.session = requests.Session()
        self.session.headers.update({'Content-Type': 'application/json'})


    def _login(self) -> None:
        """Authenticate with the management server"""
        try:
            response = self.session.post(
                f"{self.base_url}/login",
                json={"api-key": self.api_key},
                timeout=self.timeout
            )
            response.raise_for_status()
            login_data = response.json()
            self.sid = login_data['sid']
            self.api_version = login_data.get('api-server-version')
            self.session.headers.update({'X-chkp-sid': self.sid})
            log.info(f"Connected to Management API version {self.api_version}")

            # R82.20: Smart-1 Cloud may be running a background upgrade
            upgrade_message = login_data.get('background-upgrade-message')
            if upgrade_message:
                log.warning(f"Management server upgrade in progress: {upgrade_message}")

        except requests.exceptions.RequestException as e:
            log.error(f"Authentication failed: {str(e)}")
            raise

    def _logout(self) -> None:
        """Terminate management session"""
        try:
            # The API requires a JSON body, even an empty one
            response = self.session.post(f"{self.base_url}/logout", json={}, timeout=self.timeout)
            response.raise_for_status()
            log.debug("Successfully logged out")
        except requests.exceptions.RequestException as e:
            log.warning(f"Logout failed: {str(e)}")
        finally:
            self.sid = None
            self.session.headers.pop('X-chkp-sid', None)

    def _require_api_version(self) -> None:
        """Fail clearly if the server API is older than 2.1 (R82.20)"""
        try:
            parts = tuple(int(p) for p in str(self.api_version).split('.'))
        except ValueError:
            parts = ()
        if parts < REQUIRED_API_VERSION:
            raise RuntimeError(
                f"Management API {self.api_version} cannot issue cloud tokens. "
                "Gateway registration requires Management API 2.1 (Smart-1 Cloud R82.20)."
            )

    def _execute_api_call(self, endpoint: str, payload: Dict) -> Dict:
        """Generic API call handler with error checking"""
        try:
            response = self.session.post(
                f"{self.base_url}/{endpoint}",
                json=payload,
                timeout=self.timeout
            )
            response.raise_for_status()
            return response.json()

        except requests.exceptions.HTTPError as e:
            log.error(f"API call failed: {e.response.text}")
            raise
        except json.JSONDecodeError:
            log.error("Invalid JSON response from server")
            raise

    def _publish(self) -> None:
        """Publish the session and wait for the task to complete"""
        response = self._execute_api_call("publish", {})
        task_id = response.get('task-id')
        log.info("Publishing the session")
        log.debug(f"Task ID: {task_id}")
        self._monitor_task(task_id)

    def get_spark_capabilities(self) -> Dict[str, List[str]]:
        """Return the Spark versions, hardware and hardware subtypes that the tenant accepts"""
        try:
            self._login()
            caps = self._execute_api_call("show-gateway-capabilities", {"platform": "smb"})
            return {
                'versions': caps.get('supported-versions', {}).get('versions', []),
                'hardware': caps.get('supported-hardware', {}).get('hardware', []),
                'subtypes': caps.get('supported-hardware-subtypes', {}).get('hardware-subtypes', []),
            }
        finally:
            self._logout()

    def get_management_ip(self) -> str:
        """Return the internal IP address of the Smart-1 Cloud management server (100.64.x.x)"""
        try:
            self._login()
            host = self._execute_api_call("show-checkpoint-host", {"name": "Management_Service"})
            address = host.get('ipv4-address')
            if not address:
                raise ValueError("Management_Service has no IPv4 address")
            return address
        finally:
            self._logout()

    def register_gateway(self, gw_name: str, hardware: str, hardware_subtype: str, version: str) -> Dict:
        """
        Create a Spark gateway object in Smart-1 Cloud and issue its cloud token.

        The object gets an IP address generated by Smart-1 Cloud. The appliance joins
        Smart-1 Cloud with the token ('connect maas auth-token').
        """
        try:
            self._login()
            self._require_api_version()
            log.info(f"Registering gateway {gw_name} through the Management API")
            gateway = self._execute_api_call(
                "add-simple-gateway",
                {
                    "name": gw_name,
                    "hardware": hardware,
                    "hardware-subtype": hardware_subtype,
                    "version": version,
                    "os-name": "Gaia Embedded",
                    "trust-method": "cloud_token",
                    "auto-generate-ip": True,
                    "details-level": "full"
                }
            )
            token = (gateway.get('trust-details') or {}).get('authentication-token')
            if not token:
                raise ValueError(f"add-simple-gateway did not return a cloud token for {gw_name}")
            self._publish()
            log.info(f"Registered gateway {gw_name} successfully")
            return {'token': token, 'gateway_id': gateway.get('uid')}
        finally:
            self._logout()

    def configure_gateway(self, gw_name: str, sic_key: str,
                          application_control: bool = False, url_filtering: bool = False) -> None:
        """Set the SIC one-time password and blades, then publish"""
        try:
            self._login()
            # The appliance pulls its certificate ('fetch certificate'), so the management
            # server must wait for it instead of pushing the certificate
            self._execute_api_call(
                "set-simple-gateway",
                {
                    "name": gw_name,
                    "one-time-password": sic_key,
                    "trust-settings": {"initiation-phase": "when_gateway_connects"},
                    "application-control": application_control,
                    "url-filtering": url_filtering
                }
            )
            self._publish()
            log.info("Configuration changes published successfully")
        finally:
            self._logout()

    def delete_gateway(self, gw_name: str) -> bool:
        """Delete a gateway object and publish. Returns False if the object does not exist."""
        try:
            self._login()
            # ignore-warnings also removes the gateway from groups that reference it,
            # for example Playblocks_Gateways ("Object ... is used by the following objects")
            response = self.session.post(
                f"{self.base_url}/delete-simple-gateway",
                json={"name": gw_name, "ignore-warnings": True},
                timeout=self.timeout
            )
            if response.status_code == 404:
                log.info(f"Gateway object {gw_name} does not exist, nothing to delete")
                return False
            if not response.ok:
                log.error(f"API call failed: {response.text}")
            response.raise_for_status()
            self._publish()
            log.info(f"Deleted gateway object {gw_name}")
            return True
        finally:
            self._logout()

    def wait_for_sic(self, gw_names: List[str], timeout: int) -> List[str]:
        """
        Wait until SIC with each gateway is 'communicating'. Returns the gateways that are.

        Uses test-sic-status, which actively tests SIC. The 'sic-state' field of
        show-simple-gateway stays 'waiting_for_first_connection' after a Spark gateway pulls
        its certificate, until something tests the connection.
        """
        pending = list(gw_names)
        communicating: List[str] = []
        deadline = time.time() + timeout
        try:
            self._login()
            while pending:
                for gw_name in list(pending):
                    try:
                        sic_info = self._execute_api_call("test-sic-status", {"name": gw_name})
                    except requests.exceptions.RequestException as e:
                        log.warning(f"Could not test SIC with {gw_name}: {str(e)}")
                        continue
                    sic_state = sic_info.get('sic-status', 'unknown')
                    if sic_state == "communicating":
                        log.info(f"SIC established with {gw_name}")
                        pending.remove(gw_name)
                        communicating.append(gw_name)
                    else:
                        log.debug(f"{gw_name} SIC state: {sic_state}")
                if not pending or time.time() > deadline:
                    break
                log.info(f"Waiting for SIC with {', '.join(pending)}, retrying in {SIC_POLL}s")
                time.sleep(SIC_POLL)
        finally:
            self._logout()

        for gw_name in pending:
            log.error(f"SIC not established with {gw_name} within {timeout}s, skipping policy installation")
        return communicating

    def install_policy(self, policy_targets: List[str], policy_package: str) -> None:
        """Install security policy on gateways"""
        try:
            # Each operation uses its own session
            self._login()
            log.info(f"Installing {policy_package} on {len(policy_targets)} gateways")
            response = self._execute_api_call(
                "install-policy",
                {
                    "policy-package": policy_package,
                    "access": True,
                    "threat-prevention": True,
                    "targets": policy_targets
                }
            )

            task_id = response.get('task-id')
            log.info(f"Policy installation started. Task ID: {task_id}")
            self._monitor_task(task_id)

        except Exception as e:
            log.error(f"Policy installation failed: {str(e)}")
            raise
        finally:
            self._logout()

    def _monitor_task(self, task_id: str, interval: int = 10, timeout: int = TASK_TIMEOUT) -> None:
        """Monitor async task completion with spinner"""
        deadline = time.time() + timeout
        try:
            with tqdm(
                total=1,  # Fake total for spinner
                bar_format="{desc}: {elapsed} {bar}",
                ncols=80
            ) as pbar:
                while True:
                    task_status = self._execute_api_call(
                        "show-task",
                        {"task-id": task_id}
                    )

                    task_data = task_status.get('tasks', [{}])[0]
                    status = task_data.get('status', 'unknown').upper()

                    # Update spinner description
                    pbar.set_description(status)

                    if status == "SUCCEEDED":
                        pbar.set_description("COMPLETED")
                        pbar.close()
                        return
                    if status in ("FAILED", "PARTIALLY SUCCEEDED"):
                        pbar.set_description(status)
                        pbar.close()
                        raise Exception(f"Task {status.lower()}: {task_data}")
                    if time.time() > deadline:
                        pbar.close()
                        raise TimeoutError(f"Task {task_id} did not complete within {timeout}s")

                    time.sleep(interval)

        except Exception as e:
            log.error(f"Task monitoring failed: {str(e)}")
            raise

if __name__ == '__main__':
    # Example usage
    api = ManagementAPI(
        instance="your-instance",
        context="your-context",
        api_key="your-api-key"
    )
    print(api.get_spark_capabilities())
